document.addEventListener("DOMContentLoaded", () => {
  const langSelector = document.getElementById("langSelector");
  const form = document.getElementById("inquiryForm");
  const notification = document.getElementById("formNotification");

  let currentLang = localStorage.getItem("selectedLanguage") || "en";

  function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem("selectedLanguage", lang);
    document.documentElement.lang = lang;

    if (langSelector) {
      langSelector.value = lang;
    }

    const textElements = document.querySelectorAll("[data-i18n]");

    textElements.forEach((element) => {
      const key = element.getAttribute("data-i18n");

      if (translations[lang] && translations[lang][key]) {
        element.textContent = translations[lang][key];
      }
    });

    const placeholderElements = document.querySelectorAll(
      "[data-i18n-placeholder]",
    );

    placeholderElements.forEach((element) => {
      const key = element.getAttribute("data-i18n-placeholder");

      if (translations[lang] && translations[lang][key]) {
        element.setAttribute("placeholder", translations[lang][key]);
      }
    });
  }

  function showNotification(type, message) {
    if (!notification) return;

    notification.textContent = message;
    notification.className = `form-notification ${type}`;
  }

  function clearNotification() {
    if (!notification) return;

    notification.textContent = "";
    notification.className = "form-notification";
  }

  function isValidEmail(email) {
    return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
  }

  changeLanguage(currentLang);

  if (langSelector) {
    langSelector.addEventListener("change", (event) => {
      changeLanguage(event.target.value);
      clearNotification();
    });
  }

  if (form) {
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      clearNotification();

      const submitBtn = form.querySelector(".submit-btn");

      const nameInput = document.getElementById("name");
      const emailInput = document.getElementById("email");
      const interestInput = document.getElementById("interest");
      const messageInput = document.getElementById("message");

      const nameVal = nameInput.value.trim();
      const emailVal = emailInput.value.trim();
      const interestVal = interestInput.value.trim();
      const messageVal = messageInput.value.trim();

      if (
        !nameVal ||
        !emailVal ||
        !interestVal ||
        !messageVal ||
        !isValidEmail(emailVal)
      ) {
        showNotification("error", translations[currentLang]["alert-error"]);
        return;
      }

      const formData = new FormData(form);

      if (submitBtn) {
        submitBtn.disabled = true;
        submitBtn.textContent = translations[currentLang]["btn-sending"];
      }

      fetch(form.action, {
        method: "POST",
        mode: "no-cors",
        body: formData,
      })
        .then(() => {
          const successMsg = translations[currentLang]["alert-success"]
            .replace("{name}", nameVal)
            .replace("{email}", emailVal);

          showNotification("success", successMsg);
          form.reset();
        })
        .catch((error) => {
          console.error("Error submitting form:", error);
          showNotification("error", translations[currentLang]["alert-network"]);
        })
        .finally(() => {
          if (submitBtn) {
            submitBtn.disabled = false;
            submitBtn.textContent = translations[currentLang]["btn-submit"];
          }
        });
    });
  }
});
